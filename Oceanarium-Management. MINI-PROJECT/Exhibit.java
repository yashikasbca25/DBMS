    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String name = txtExhibit.getText().trim();
String location = txtLocation.getText().trim();
String description = txtDescription.getText().trim();

try {
    Connection con = getConnection();
    if (con == null) return;

    String sql = "INSERT INTO exhibits "
            + "(exhibit_name, location, description) "
            + "VALUES (?, ?, ?)";

    PreparedStatement pst = con.prepareStatement(sql);
    pst.setString(1, name);
    pst.setString(2, location);
    pst.setString(3, description);

    pst.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Exhibit added successfully!");

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        try {
    Connection con = getConnection();
    if (con == null) return;

    String sql = "SELECT * FROM exhibits";
    PreparedStatement pst = con.prepareStatement(sql);
    ResultSet rs = pst.executeQuery();

    DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("exhibit_id"),
            rs.getString("exhibit_name"),
            rs.getString("location"),
            rs.getString("description")
        });
    }

    rs.close();
    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnViewActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String exhibitId = JOptionPane.showInputDialog(this,
        "Enter Exhibit ID to update:");

if (exhibitId == null || exhibitId.trim().isEmpty()) return;

String name = txtExhibit.getText().trim();
String location = txtLocation.getText().trim();
String description = txtDescription.getText().trim();

try {
    Connection con = getConnection();
    if (con == null) return;

    String sql = "UPDATE exhibits SET exhibit_name=?, "
            + "location=?, description=? WHERE exhibit_id=?";

    PreparedStatement pst = con.prepareStatement(sql);
    pst.setString(1, name);
    pst.setString(2, location);
    pst.setString(3, description);
    pst.setInt(4, Integer.parseInt(exhibitId));

    int rows = pst.executeUpdate();

    JOptionPane.showMessageDialog(this,
            rows > 0 ? "Exhibit updated successfully!" :
            "Exhibit ID not found!");

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String exhibitId = JOptionPane.showInputDialog(this,
        "Enter Exhibit ID to delete:");

if (exhibitId == null || exhibitId.trim().isEmpty()) return;

try {
    Connection con = getConnection();
    if (con == null) return;

    String sql = "DELETE FROM exhibits WHERE exhibit_id=?";
    PreparedStatement pst = con.prepareStatement(sql);

    pst.setInt(1, Integer.parseInt(exhibitId));

    int rows = pst.executeUpdate();

    JOptionPane.showMessageDialog(this,
            rows > 0 ? "Exhibit deleted successfully!" :
            "Exhibit ID not found!");

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

