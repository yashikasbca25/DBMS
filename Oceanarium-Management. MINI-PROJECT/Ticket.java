    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String visitorId = txtVisitorID.getText().trim();
String ticketType = txtTicketType.getText().trim();
String price = txtPrice.getText().trim();
String visitDate = txtDate.getText().trim();

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "INSERT INTO tickets "
            + "(visitor_id, ticket_type, price, visit_date) "
            + "VALUES (?, ?, ?, ?)";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setInt(1, Integer.parseInt(visitorId));
    pst.setString(2, ticketType);
    pst.setDouble(3, Double.parseDouble(price));
    pst.setDate(4, java.sql.Date.valueOf(visitDate));

    pst.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Ticket added successfully!");

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "SELECT * FROM tickets";

    PreparedStatement pst = con.prepareStatement(sql);
    ResultSet rs = pst.executeQuery();

    DefaultTableModel model =
            (DefaultTableModel) jTable2.getModel();

    model.setRowCount(0);

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("ticket_id"),
            rs.getInt("visitor_id"),
            rs.getString("ticket_type"),
            rs.getDouble("price"),
            rs.getDate("visit_date")
        });
    }

    rs.close();
    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnViewActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String ticketId = JOptionPane.showInputDialog(this,
        "Enter Ticket ID to update:");

if (ticketId == null || ticketId.trim().isEmpty()) {
    return;
}

String visitorId = txtVisitorID.getText().trim();
String ticketType = txtTicketType.getText().trim();
String price = txtPrice.getText().trim();
String visitDate = txtDate.getText().trim();

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "UPDATE tickets SET visitor_id=?, "
            + "ticket_type=?, price=?, visit_date=? "
            + "WHERE ticket_id=?";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setInt(1, Integer.parseInt(visitorId));
    pst.setString(2, ticketType);
    pst.setDouble(3, Double.parseDouble(price));
    pst.setDate(4, java.sql.Date.valueOf(visitDate));
    pst.setInt(5, Integer.parseInt(ticketId));

    int rows = pst.executeUpdate();

    if (rows > 0) {
        JOptionPane.showMessageDialog(this,
                "Ticket updated successfully!");
    } else {
        JOptionPane.showMessageDialog(this,
                "Ticket ID not found!");
    }

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String ticketId = JOptionPane.showInputDialog(this,
        "Enter Ticket ID to delete:");

if (ticketId == null || ticketId.trim().isEmpty()) {
    return;
}

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "DELETE FROM tickets WHERE ticket_id=?";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setInt(1, Integer.parseInt(ticketId));

    int rows = pst.executeUpdate();

    if (rows > 0) {
        JOptionPane.showMessageDialog(this,
                "Ticket deleted successfully!");
    } else {
        JOptionPane.showMessageDialog(this,
                "Ticket ID not found!");
    }

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

