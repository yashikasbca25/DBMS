    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String name = txtAnimalName.getText();
String species = txtSpecies.getText();
String habitat = txthabitat.getText();
String food = txtFoodType.getText();

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "INSERT INTO marine_animals "
            + "(animal_name, species, habitat, food_type) "
            + "VALUES (?, ?, ?, ?)";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, name);
    pst.setString(2, species);
    pst.setString(3, habitat);
    pst.setString(4, food);

    pst.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Animal added successfully!");

    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "SELECT * FROM marine_animals";
    PreparedStatement pst = con.prepareStatement(sql);
    java.sql.ResultSet rs = pst.executeQuery();

    DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("animal_id"),
            rs.getString("animal_name"),
            rs.getString("species"),
            rs.getString("habitat"),
            rs.getString("food_type")
        });
    }

    rs.close();
    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnViewActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String id = JOptionPane.showInputDialog(
        this, "Enter Animal ID to update:");

if (id == null || id.trim().isEmpty()) {
    return;
}

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "UPDATE marine_animals SET animal_name=?, "
            + "species=?, habitat=?, food_type=? WHERE animal_id=?";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, txtAnimalName.getText());
    pst.setString(2, txtSpecies.getText());
    pst.setString(3, txthabitat.getText());
    pst.setString(4, txtFoodType.getText());
    pst.setInt(5, Integer.parseInt(id));

    int rows = pst.executeUpdate();

    if (rows > 0) {
        JOptionPane.showMessageDialog(this,
                "Animal updated successfully!");
    } else {
        JOptionPane.showMessageDialog(this,
                "Animal ID not found!");
    }

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String id = JOptionPane.showInputDialog(
        this, "Enter Animal ID to delete:");

if (id == null || id.trim().isEmpty()) {
    return;
}

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "DELETE FROM marine_animals WHERE animal_id = ?";
    PreparedStatement pst = con.prepareStatement(sql);

    pst.setInt(1, Integer.parseInt(id));

    int rows = pst.executeUpdate();

    if (rows > 0) {
        JOptionPane.showMessageDialog(this,
                "Animal deleted successfully!");
    } else {
        JOptionPane.showMessageDialog(this,
                "Animal ID not found!");
    }

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

