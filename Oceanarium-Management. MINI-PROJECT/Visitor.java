    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String name = txtVisitorName.getText();
String age = txtAge.getText().trim();
String phone = txtPhone.getText();

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "INSERT INTO visitors "
            + "(visitor_name, age, phone) VALUES (?, ?, ?)";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, name);
    
    System.out.println("Age entered: [" + age + "]");
    pst.setInt(2, Integer.parseInt(age));
    pst.setString(3, phone);

    pst.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Visitor added successfully!");

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "SELECT * FROM visitors";
    PreparedStatement pst = con.prepareStatement(sql);
    java.sql.ResultSet rs = pst.executeQuery();

    DefaultTableModel model =
            (DefaultTableModel) tblVisitors.getModel();

    model.setRowCount(0);

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("visitor_id"),
            rs.getString("visitor_name"),
            rs.getInt("age"),
            rs.getString("phone")
        });
    }

    rs.close();
    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnViewActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String id = JOptionPane.showInputDialog(
        this, "Enter Visitor ID to update:");

if (id == null || id.trim().isEmpty()) {
    return;
}

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "UPDATE visitors SET visitor_name=?, "
            + "age=?, phone=? WHERE visitor_id=?";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, txtVisitorName.getText());
    pst.setInt(2, Integer.parseInt(txtAge.getText().trim()));
    pst.setString(3, txtPhone.getText());
    pst.setInt(4, Integer.parseInt(id));

    int rows = pst.executeUpdate();

    if (rows > 0) {
        JOptionPane.showMessageDialog(this,
                "Visitor updated successfully!");
    } else {
        JOptionPane.showMessageDialog(this,
                "Visitor ID not found!");
    }

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String id = JOptionPane.showInputDialog(
        this, "Enter Visitor ID to delete:");

if (id == null || id.trim().isEmpty()) {
    return;
}

try {
    Connection con = getConnection();

    if (con == null) {
        return;
    }

    String sql = "DELETE FROM visitors WHERE visitor_id = ?";
    PreparedStatement pst = con.prepareStatement(sql);

    pst.setInt(1, Integer.parseInt(id));

    int rows = pst.executeUpdate();

    if (rows > 0) {
        JOptionPane.showMessageDialog(this,
                "Visitor deleted successfully!");
    } else {
        JOptionPane.showMessageDialog(this,
                "Visitor ID not found!");
    }

    pst.close();
    con.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

